import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {join} from 'node:path';

export async function checkRetention({evaluate,waitFor,waitUntil,sleep,commands,holdReads,releaseReads,setFixture,getFixture}) {
  await waitFor('Saved detail content stays readable.');
  await (await import('./source-expiry.mjs')).checkSourceExpiry({evaluate,waitUntil});
  const deadline=()=>new Date(Date.now()+60_000).toISOString();
  const saved={id:'paid_text',feature:'x_posts',text:'Surviving paid output.',expiresAt:deadline(),retentionMode:'while_paid'};
  const focus=()=>evaluate(`window.dispatchEvent(new Event('focus'))`);
  const reads=()=>commands.filter(call=>call==='GET /v1/projects/detail_fixture/outputs').length;
  setFixture({mode:'ready',savedOutputs:[saved],retentionAvailability:{transcriptRetentionMode:'while_paid',transcriptExpiresAt:deadline()}});
  await focus();await waitFor('Surviving paid output.');await waitFor('Available while your paid access continues.');
  await evaluate(`document.querySelector('a[aria-label="Project settings"]').click()`);
  await waitFor('Transcript available while your paid access continues.');
  await evaluate(`document.querySelector('.project-settings-page .back-link').click()`);await waitFor('Surviving paid output.');
  const before=reads();
  saved.retentionMode='fixed';
  getFixture().accessExpired=true;
  getFixture().retentionAvailability.transcriptRetentionMode='fixed';
  await evaluate(`document.dispatchEvent(new Event('visibilitychange'))`);
  await waitFor('Available until');
  assert.ok(reads()>before,'visible page rereads outputs');
  assert.equal(await evaluate(`document.querySelector('.output-copy').textContent`),'Surviving paid output.','inactive access preserves retained reads');
  getFixture().accessExpired=false;
  const media={id:'paid_media',feature:'carousels',text:'',expiresAt:deadline(),assets:[{id:'slide1',contentType:'image/png',downloadPath:'/v1/projects/detail_fixture/outputs/paid_media/assets/slide1/download'}]};
  getFixture().savedOutputs=[media];
  await evaluate(`window.__retentionRevoked=[];const oldRevoke=URL.revokeObjectURL.bind(URL);URL.revokeObjectURL=url=>{window.__retentionRevoked.push(url);oldRevoke(url)}`);
  await focus();await waitFor('Download PNG');await waitUntil(`document.querySelector('.slide-preview img')?.naturalWidth===1`,'private asset loaded');
  media.expiresAt=new Date(Date.now()+700).toISOString();
  await focus();await sleep(250);
  const boundaryReads=reads();
  await waitUntil(`!document.querySelector('.output-paper')`,'expired selection removed at clock boundary');
  await waitUntil(`window.__retentionRevoked.length>0`,'expired private object URL revoked');
  await sleep(150);
  assert.ok(reads()>boundaryReads,'clock boundary refreshes canonical outputs');
  const pendingPath='/v1/projects/detail_fixture/outputs/pending_media/assets/slide1/download';
  holdReads.add(pendingPath);
  await evaluate(`window.__retentionCreated=[];const oldCreate=URL.createObjectURL.bind(URL);URL.createObjectURL=blob=>{const url=oldCreate(blob);window.__retentionCreated.push(url);return url}`);
  getFixture().savedOutputs=[{...media,id:'pending_media',expiresAt:new Date(Date.now()+700).toISOString(),assets:[{...media.assets[0],downloadPath:pendingPath}]}];
  await focus();await waitFor('Opening private file');
  await waitUntil(`!document.querySelector('.output-paper')`,'pending media expires');
  await releaseReads();await sleep(150);
  assert.equal(await evaluate(`window.__retentionCreated.length`),0,'an aborted expired response cannot create an object URL');
  getFixture().savedOutputs=[{...saved,expiresAt:deadline()}];
  getFixture().retentionAvailability={sourceAvailable:false,transcriptAvailable:true,sourceExpiresAt:new Date(Date.now()-1000).toISOString(),transcriptExpiresAt:deadline()};
  await focus();await waitFor('Surviving paid output.');
  assert.equal(await evaluate(`document.body.innerText.includes('Restore')`),false);
  assert.equal(await evaluate(`document.querySelector('.generation-format > button')?.disabled`),false,'server permits transcript-based creation after source expiry');
  await evaluate(`document.querySelector('a[aria-label="Project settings"]').click()`);await waitFor('Transcript available until');await waitFor('eligible formats from your transcript');
  assert.equal(await evaluate(`document.querySelector('.project-settings-page a[target="_blank"]').href`),'https://drive.google.com/file/d/test_video/view','original source link remains usable');
  await evaluate(`document.querySelector('.project-settings-page .back-link').click()`);await waitFor('Surviving paid output.');
  assert.deepEqual(commands.filter(call=>['/v1/capabilities','/v1/usage','/v1/brand','/v1/drive/connection'].includes(call.slice(4))),[]);
  getFixture().savedOutputs=[{...media,expiresAt:deadline()}];
  await focus();await waitFor('Download PNG');
  const revokedBefore=await evaluate(`window.__retentionRevoked.length`);
  await evaluate(`(async()=>{const{firebaseAuth}=await import('/src/shared/auth/firebase.ts');const{signOut}=await import('/node_modules/.vite/deps/firebase_auth.js');await signOut(firebaseAuth());})()`);
  await waitUntil(`window.__retentionRevoked.length>${revokedBefore}`,'owner change revokes private media');
  assert.equal(await evaluate(`!!document.querySelector('.output-paper')`),false);
  await writeFile(join(process.env.RIFLO_SMOKE_ARTIFACTS,'retention-checks.json'),JSON.stringify({checks:['while-paid/fixed copy','inactive retained reads','focus and visibility canonical reads','clock expiry removes selection','private URL revoked on expiry and owner change','aborted expired response discarded','retained transcript format authority','no account API requests'],commands},null,2));
  console.log('PASS: retention copy, focus/visibility/clock refresh, inactive saved reads, expired media cleanup and retained transcript authority (isolated API fixtures).');
}
